def _style(plt):
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.size": 8,
            "axes.edgecolor": MUTED,
            "axes.labelcolor": INK,
            "axes.linewidth": 0.6,
            "xtick.color": MUTED,
            "ytick.color": MUTED,
            "axes.grid": True,
            "grid.color": GRID,
            "grid.linewidth": 0.5,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "legend.frameon": False,
            "lines.linewidth": 1.4,
            "pdf.fonttype": 42,
        }
    )


def fig_pilot_curves(results, plt):
    chosen = ["real_fixed_filter_baseline_v6", "real_filter_v6", "main_v15_multi_fallback", "main_v17_garbled_filter_fallback"]
    by_name = {Path(r["path"]).name: r for r in results}
    figure, axes = plt.subplots(2, 2, figsize=(7.0, 4.2), sharex=True, sharey=True)
    for axis, name in zip(axes.flat, chosen):
        series = by_name[name]["series"]
        axis.plot(series["generation"], series["smoothed_compliance_rate"], color=BLUE, label="Compliance rate")
        axis.plot(series["generation"], series["smoothed_attack_progress"], color=ORANGE, label="Attack progress")
        for update in series["filter_update_generations"]:
            axis.axvline(update, color=MUTED, linestyle=":", linewidth=0.8)
        axis.set_title(RUN_LABELS[name], fontsize=8, color=INK)
        axis.set_ylim(0, 1)
    for axis in axes[1]:
        axis.set_xlabel("Generation")
    for axis in axes[:, 0]:
        axis.set_ylabel("Offspring rate (5-gen. mean)")
    axes[0, 0].legend(loc="upper left", fontsize=7)
    figure.tight_layout()
    figure.savefig(FIG / "pilot_curves.pdf")
    plt.close(figure)


def fig_gate_losses(results, plt):
    labels, near, other = [], [], []
    for result in results:
        name = Path(result["path"]).name
        gates = result["quality_gate_rejections_per_parent_slot"]
        labels.append(RUN_LABELS[name].replace(" (fixed)", "\n(fixed)"))
        near.append(gates.get("near_duplicate", 0.0))
        other.append(sum(v for k, v in gates.items() if k != "near_duplicate"))
    figure, axis = plt.subplots(figsize=(7.0, 2.4))
    x = range(len(labels))
    axis.bar(x, near, color=BLUE, width=0.62, label="Near-duplicate (sticky mark)")
    axis.bar(x, other, bottom=near, color=ORANGE, width=0.62, label="Other quality gates",
             edgecolor="white", linewidth=1.0)
    axis.set_xticks(list(x), labels, fontsize=7)
    axis.set_ylim(0, 1.08)
    axis.set_ylabel("Invalid share of parent slots")
    axis.legend(loc="upper center", ncol=2, fontsize=7, bbox_to_anchor=(0.5, 1.18))
    figure.tight_layout()
    figure.savefig(FIG / "gate_losses.pdf")
    plt.close(figure)


def fig_filter_events(results, plt):
    window = range(-5, 6)
    aligned = defaultdict(list)
    for result in results:
        series = result["series"]
        index = {g: i for i, g in enumerate(series["generation"])}
        for update in series["filter_update_generations"]:
            for offset in window:
                g = update + offset
                if g in index:
                    aligned[offset].append(series["compliance_rate"][index[g]])
    offsets = [o for o in window if aligned[o]]
    means = [statistics.mean(aligned[o]) for o in offsets]
    lows = [statistics.quantiles(aligned[o], n=4)[0] if len(aligned[o]) > 1 else aligned[o][0] for o in offsets]
    highs = [statistics.quantiles(aligned[o], n=4)[2] if len(aligned[o]) > 1 else aligned[o][0] for o in offsets]
    figure, axis = plt.subplots(figsize=(3.4, 2.4))
    axis.fill_between(offsets, lows, highs, color=BLUE, alpha=0.18, linewidth=0, label="Interquartile range")
    axis.plot(offsets, means, color=BLUE, marker="o", markersize=3, label="Mean")
    axis.axvline(0, color=MUTED, linestyle=":", linewidth=0.8)
    axis.set_xlabel("Generations relative to accepted filter update")
    axis.set_ylabel("Offspring compliance rate")
    axis.legend(fontsize=7, loc="upper right")
    figure.tight_layout()
    figure.savefig(FIG / "filter_events.pdf")
    plt.close(figure)
    return len(aligned[0])


def fig_ab(histories, plt):
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.5))
    for arm, color, label in (("legacy", ORANGE, "Legacy controls"), ("improved", BLUE, "Proposed controls")):
        runs = histories[arm]
        length = min(len(run) for run in runs)
        generations = [runs[0][i]["generation"] for i in range(length)]
        for axis, key in zip(axes, ("offspring_attack_success_rate", "population_diversity")):
            values = [[run[i][key] for run in runs] for i in range(length)]
            means = [statistics.mean(v) for v in values]
            if key == "offspring_attack_success_rate":
                means = _trailing_mean(means, 5)
            low = [min(v) for v in values]
            high = [max(v) for v in values]
            if key != "offspring_attack_success_rate":
                axis.fill_between(generations, low, high, color=color, alpha=0.15, linewidth=0)
            axis.plot(generations, means, color=color, label=label)
    axes[0].set_ylabel("Offspring success rate (5-gen. mean)")
    axes[1].set_ylabel("Population diversity")
    for axis in axes:
        axis.set_xlabel("Generation")
    axes[0].legend(fontsize=7, loc="upper right")
    figure.tight_layout()
    figure.savefig(FIG / "simulated_ab.pdf")
    plt.close(figure)


def _trailing_mean(values, window):
    return [statistics.mean(values[max(0, i - window + 1): i + 1]) for i in range(len(values))]


def main() -> int:
    GEN.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    numbers = Numbers()
    seed_gate_audit(numbers)
    seed_labels(numbers)
    calibration(numbers)
    results = pilot(numbers)
    histories = ab(numbers)
    budget(numbers)
    simulator(numbers)

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _style(plt)
    fig_pilot_curves(results, plt)
    fig_gate_losses(results, plt)
    numbers["shockEventsAtZero"] = fig_filter_events(results, plt)
    fig_ab(histories, plt)
    numbers.write(GEN / "numbers.tex")
    print((GEN / "numbers.tex").read_text())
    return 0


