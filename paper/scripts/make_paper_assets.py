def seed_gate_audit(numbers: Numbers):
    legacy = load_legacy_gates()
    results = {}
    for name, gates in (("legacy", legacy.apply_quality_constraints), ("current", apply_quality_constraints)):
        seeds = load_prompt_population(str(ROOT / "prompts" / "initial_population.csv"))
        for prompt in seeds:
            prompt.output_prompts = ["controlled filtered output"]
            prompt.direct_output = "controlled direct output"
        reasons = gates(seeds)
        valid = int(sum(p.metrics["valid"] for p in seeds))
        results[name] = {"total": len(seeds), "valid": valid, "reasons": dict(reasons)}
    numbers["seedPoolSize"] = results["current"]["total"]
    numbers["seedValidLegacy"] = results["legacy"]["valid"]
    numbers["seedValidCurrent"] = results["current"]["valid"]
    numbers["seedGarbledLegacy"] = results["legacy"]["reasons"].get("garbled_tokens", 0)
    numbers["seedGarbledLegacyPct"] = pct(
        results["legacy"]["reasons"].get("garbled_tokens", 0) / results["legacy"]["total"]
    )
    return results


def seed_labels(numbers: Numbers):
    import ast

    structure, content = Counter(), Counter()
    with (ROOT / "prompts" / "initial_population.csv").open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            for label in ast.literal_eval(row["structure_labels"]):
                structure[label] += 1
            for label in ast.literal_eval(row["labels"]):
                content[label] += 1
    rows = []
    for kind, counter in (("Structure", structure), ("Content", content)):
        for label, count in counter.most_common():
            rows.append(f"{kind} & \\texttt{{{label.replace('_', chr(92) + '_')}}} & {count} \\\\")
    (GEN / "seed_labels.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    return structure, content


def calibration(numbers: Numbers):
    fixtures = json.loads((ROOT / "tests" / "fixtures" / "attack_evaluator_calibration.json").read_text())
    if isinstance(fixtures, dict):
        fixtures = fixtures.get("fixtures", fixtures.get("items", []))
    report = calibration_confusion_matrix(DefensiveComplianceEvaluator(), fixtures)
    numbers["calibTotal"] = report["total"]
    numbers["calibCorrect"] = report["correct"]
    labels = report["labels"]
    rows = []
    for expected in labels:
        cells = [str(report["confusion_matrix"][expected][predicted]) for predicted in labels]
        rows.append(f"\\texttt{{{expected.replace('_', chr(92) + '_')}}} & " + " & ".join(cells) + " \\\\")
    (GEN / "calibration.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")


def rescored_label_mix(run_dirs, evaluator):
    labels = Counter()
    pattern_share = {}
    for run_dir in run_dirs:
        patterns = Counter()
        compliant = 0
        with (run_dir / "samples.jsonl").open(encoding="utf-8") as handle:
            for line in handle:
                row = json.loads(line)
                if row.get("kind") != "filtered" or row.get("status") != "valid":
                    continue
                result = evaluator.evaluate(row.get("text", ""))
                labels[result.label] += 1
                if result.label == "compliant":
                    compliant += 1
                    matched = result.metadata["signals"]["harmful_operational_patterns"]
                    if matched:
                        patterns[matched[0]] += 1
        pattern_share[run_dir.name] = (
            patterns.most_common(1)[0][1] / compliant if compliant and patterns else None
        )
    return labels, pattern_share


def operator_noop_share(run_dir: Path):
    path = run_dir / "generation_summary.csv"
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    attempts = sum(float(r.get("operator_attempts") or 0) for r in rows)
    noops = sum(float(r.get("operator_noops") or 0) for r in rows)
    return noops / attempts if attempts else None


def pilot(numbers: Numbers):
    evaluator = DefensiveComplianceEvaluator()
    run_dirs = [ROOT / "outputs" / name for name in PILOT_SERIES]
    results = [analyze_run(run_dir, evaluator, 5) for run_dir in run_dirs]
    labels, pattern_share = rescored_label_mix(run_dirs, evaluator)
    registry = json.loads((ROOT / "experiments" / "invalid_runs.json").read_text())
    quarantined = {Path(entry["path"]).name for entry in registry.get("runs", [])}

    table = []
    near_dup, noop_shares = [], []
    for run_dir, result in zip(run_dirs, results):
        config = json.loads((run_dir / "config.json").read_text())
        args = config["args"]
        gates = result["quality_gate_rejections_per_parent_slot"]
        nd = gates.get("near_duplicate", 0.0)
        other = float(sum(v for k, v in gates.items() if k != "near_duplicate"))
        near_dup.append(nd)
        noop = operator_noop_share(run_dir)
        if noop is not None:
            noop_shares.append(noop)
        label = RUN_LABELS[run_dir.name] + ("$^{\\dagger}$" if run_dir.name in quarantined else "")
        model = str(args.get("model"))
        model = {"dphn/Dolphin3.0-Llama3.1-8B": "Dolphin", "dolphin": "Dolphin"}.get(model, model)
        table.append(
            " & ".join(
                [
                    label,
                    model.replace("_", "\\_"),
                    str(args.get("filter_update_every") or 0),
                    str(result["filter_updates"]),
                    str(result["filtered_samples"]),
                    fmt(result["overall_compliance_rate"]),
                    fmt(result["early_quarter_compliance_rate"]),
                    fmt(result["late_quarter_compliance_rate"]),
                    fmt(result["first_compliant_generation"]),
                    fmt(result["t90_generation"]),
                    fmt(nd, 2),
                    fmt(other, 2),
                    f"{fmt(result['diversity_start'], 2)}$\\to${fmt(result['diversity_end'], 2)}",
                ]
            )
            + " \\\\"
        )
    (GEN / "pilot_table.tex").write_text("\n".join(table) + "\n", encoding="utf-8")

    total = sum(labels.values())
    for key, name in (
        ("refusal", "Refusal"),
        ("benign_educational", "Benign"),
        ("ambiguous", "Ambiguous"),
        ("compliant", "Compliant"),
    ):
        numbers[f"pilotShare{name}"] = pct(labels.get(key, 0) / total)
    numbers["pilotSamples"] = f"{total:,}".replace(",", "{,}")
    numbers["pilotRuns"] = len(run_dirs)
    numbers["pilotNearDupMin"] = pct(min(near_dup), 0)
    numbers["pilotNearDupMax"] = pct(max(near_dup), 0)
    numbers["pilotNoopMin"] = pct(min(noop_shares), 0)
    numbers["pilotNoopMax"] = pct(max(noop_shares), 0)
    worst = max((v for v in pattern_share.values() if v is not None), default=None)
    numbers["pilotTopPatternShareMax"] = pct(worst, 0) if worst is not None else "[not measured]"

    leads = [
        r["progress_compliance_correlation"]["noncompliant_progress_to_compliance_lag3"]
        for r in results
        if r["progress_compliance_correlation"]["noncompliant_progress_to_compliance_lag3"] is not None
    ]
    same = [
        r["progress_compliance_correlation"]["same_generation"]
        for r in results
        if r["progress_compliance_correlation"]["same_generation"] is not None
    ]
    numbers["progressLeadMedian"] = f"{statistics.median(leads):.2f}"
    numbers["progressLeadPositive"] = sum(v > 0 for v in leads)
    numbers["progressLeadCount"] = len(leads)
    numbers["progressSameMedian"] = f"{statistics.median(same):.2f}"

    shocks = [s for r in results for s in r["filter_shocks"]]
    drops = [s["drop"] for s in shocks]
    recoveries = [s["generations_to_half_recovery"] for s in shocks if s["generations_to_half_recovery"] is not None]
    numbers["shockCount"] = len(shocks)
    numbers["shockMedianDrop"] = f"{statistics.median(drops):.3f}"
    numbers["shockRecoveredWithinOne"] = sum(1 for v in recoveries if v <= 1)
    numbers["shockRecoverable"] = len(recoveries)
    return results


def ab(numbers: Numbers):
    base = ROOT / "outputs" / "simulated_ab"
    summary = json.loads((base / "ab_summary.json").read_text())
    with (base / "ab_runs.csv").open(newline="", encoding="utf-8") as handle:
        runs = list(csv.DictReader(handle))
    rows = []
    metrics = [
        ("mean_offspring_success", "Mean offspring success rate", 3),
        ("early_offspring_success", "Early-quarter offspring success rate", 3),
        ("late_offspring_success", "Late-quarter offspring success rate", 3),
        ("late_offspring_progress", "Late-quarter offspring progress", 3),
        ("zero_best_generations", "Generations with best fitness $=0$", 1),
        ("final_parent_lineages", "Surviving seed lineages (final)", 1),
        ("final_population_diversity", "Population diversity (final)", 2),
        ("best_ever_fitness", "Best fitness ever observed", 3),
        ("llm_calls", "Model calls", 0),
        ("filter_versions", "Accepted filter updates", 1),
    ]
    for key, label, digits in metrics:
        legacy, improved = summary["legacy"][key], summary["improved"][key]
        wins = sum(
            1
            for seed in {r["seed"] for r in runs}
            if _seed_value(runs, "improved", seed, key) > _seed_value(runs, "legacy", seed, key)
        )
        rows.append(
            f"{label} & {legacy:.{digits}f} & {improved:.{digits}f} & {wins}/{len({r['seed'] for r in runs})} \\\\"
        )
    (GEN / "ab_table.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    numbers["abSeeds"] = len({r["seed"] for r in runs})
    numbers["abLegacyMeanSuccess"] = f"{summary['legacy']['mean_offspring_success']:.3f}"
    numbers["abImprovedMeanSuccess"] = f"{summary['improved']['mean_offspring_success']:.3f}"
    numbers["abRelativeGain"] = pct(
        summary["improved"]["mean_offspring_success"] / summary["legacy"]["mean_offspring_success"] - 1.0, 0
    )
    numbers["abLegacyLineages"] = f"{summary['legacy']['final_parent_lineages']:.0f}"
    numbers["abImprovedLineages"] = f"{summary['improved']['final_parent_lineages']:.0f}"
    numbers["abLegacyDiversity"] = f"{summary['legacy']['final_population_diversity']:.2f}"
    numbers["abImprovedDiversity"] = f"{summary['improved']['final_population_diversity']:.2f}"
    numbers["abLegacyCalls"] = f"{summary['legacy']['llm_calls']:.0f}"
    numbers["abImprovedCalls"] = f"{summary['improved']['llm_calls']:.0f}"
    histories = {}
    for arm in ("legacy", "improved"):
        histories[arm] = []
        for run_dir in sorted(base.glob(f"{arm}_seed*")):
            with (run_dir / "history.jsonl").open(encoding="utf-8") as handle:
                histories[arm].append([json.loads(line) for line in handle if line.strip()])
    return histories


def _seed_value(runs, arm, seed, key):
    for row in runs:
        if row["arm"] == arm and row["seed"] == seed:
            return float(row[key])
    return float("nan")


def simulator(numbers: Numbers):
    from experiments.simulated_target import SimulatedTargetClient, _sigmoid

    client = SimulatedTargetClient()
    with (ROOT / "prompts" / "initial_population.csv").open(encoding="utf-8") as handle:
        texts = [row["text"] for row in csv.DictReader(handle)]
    base_filter = "You are a helpful assistant."
    rates = [_sigmoid(client.susceptibility(text, base_filter) - client.difficulty) for text in texts]
    numbers["simDifficulty"] = f"{client.difficulty:.1f}"
    numbers["simBaseRate"] = pct(statistics.mean(rates))


def budget(numbers: Numbers):
    from argparse import Namespace

    spec = importlib.util.spec_from_file_location("estimate_budget", ROOT / "scripts" / "estimate_budget.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    args = Namespace(
        mu=16, lambda_=64, generations=300, k_evals=3, parent_resample_k=1,
        max_samples_per_prompt=12, filter_update_every=15, filter_warmup_generations=30,
        top_k_filter=8, benign_prompts=40, candidate_rules=4, final_k_evals=16,
        duplicate_share=0.05, seconds_per_call=2.5, concurrency=8,
    )
    result = module.estimate(args)
    numbers["budgetCalls"] = f"{result['total_calls']:,}".replace(",", "{,}")
    numbers["budgetHours"] = result["estimated_hours"]
    numbers["budgetHoursSequential"] = result["estimated_hours_sequential"]
    numbers["budgetSearchCalls"] = f"{result['search_calls']:,}".replace(",", "{,}")
    numbers["budgetFilterCalls"] = f"{result['filter_update_calls']:,}".replace(",", "{,}")
    numbers["budgetResampleCalls"] = f"{result['parent_resample_calls']:,}".replace(",", "{,}")


